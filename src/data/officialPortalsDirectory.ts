export function getSuggestedPortalsForCountry(countryId: string): OfficialGovernmentPortal[] {
  return OFFICIAL_GOVERNMENT_PORTALS.filter(
    (p) => p.countryId.toLowerCase() === countryId.toLowerCase()
  );
}

export function findPortalByAuthority(authority: string, countryId?: string): OfficialGovernmentPortal | undefined {
  const norm = authority.toLowerCase();
  return OFFICIAL_GOVERNMENT_PORTALS.find((p) => {
    const matchCountry = !countryId || p.countryId.toLowerCase() === countryId.toLowerCase();
    const matchAuth =
      norm.includes(p.authorityShort.toLowerCase()) ||
      p.authority.toLowerCase().includes(norm) ||
      norm.includes(p.authority.toLowerCase());
    return matchCountry && matchAuth;
  });
}
