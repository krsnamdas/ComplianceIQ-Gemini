// Helper to compute quarterly summaries with scale multiplier
export function computeQuarterlySummaries(
  milestones: RoadmapMilestone[],
  scaleMultiplier: number = 1.0
): QuarterlySummary[] {
  return ROADMAP_QUARTERS.map((q) => {
    const qMilestones = milestones.filter((m) => m.quarter === q.id);
    const criticalCount = qMilestones.filter((m) => m.urgency === 'Critical').length;
    const highCount = qMilestones.filter((m) => m.urgency === 'High').length;
    const mediumCount = qMilestones.filter((m) => m.urgency === 'Medium').length;

    const totalInvestmentUSD = Math.round(
      qMilestones.reduce((acc, m) => acc + m.baseInvestmentUSD * scaleMultiplier, 0)
    );
    const totalCapexUSD = Math.round(
      qMilestones.reduce((acc, m) => acc + m.capexUSD * scaleMultiplier, 0)
    );
    const totalOpexUSD = Math.round(
      qMilestones.reduce((acc, m) => acc + m.opexUSD * scaleMultiplier, 0)
    );
    const totalFteMonths = Number(
      qMilestones.reduce((acc, m) => acc + m.fteRequirementMonths * (scaleMultiplier >= 1.5 ? 1.4 : scaleMultiplier <= 0.7 ? 0.7 : 1.0), 0).toFixed(1)
    );

    const authoritiesSet = new Set<string>();
    qMilestones.forEach((m) => authoritiesSet.add(m.authorityShort));
    const topAuthorities = Array.from(authoritiesSet);

    return {
      quarter: q.id,
      quarterLabel: q.label,
      year: q.year,
      milestones: qMilestones,
      milestoneCount: qMilestones.length,
      criticalCount,
      highCount,
      mediumCount,
      totalInvestmentUSD,
      totalCapexUSD,
      totalOpexUSD,
      totalFteMonths,
      topAuthorities,
    };
  });
}
